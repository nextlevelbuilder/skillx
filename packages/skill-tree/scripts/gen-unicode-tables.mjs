#!/usr/bin/env node
/**
 * Generates src/unicode-15-tables.ts, the Unicode 15.0.0 tables of the
 * skill-tree path rules (contract 4.3), from two pinned inputs:
 *
 * - fixtures/ucd/CaseFolding-15.0.0.txt, the Unicode 15.0.0 data file, also
 *   committed by AgentKit as the source of its fold table;
 * - scripts/unicode-15.0.0-go.json, written by dump-go-unicode.go from the Go
 *   unicode and x/text norm tables (Unicode 15.0.0) that the AgentKit
 *   reference implementation uses for category and normalization.
 *
 *   node scripts/gen-unicode-tables.mjs
 *
 * Each input must match its pinned sha256, so the output is reproducible and
 * cannot silently move to another Unicode version.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "15.0.0";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const INPUTS = {
  caseFolding: {
    path: "fixtures/ucd/CaseFolding-15.0.0.txt",
    sha256: "cdd49e55eae3bbf1f0a3f6580c974a0263cb86a6a08daa10fbf705b4808a56f7",
  },
  goTables: {
    path: "scripts/unicode-15.0.0-go.json",
    sha256: "0d0155948ceea434fa241b59937db1a41689fa2ccb8231d35d96a2c56f57b52b",
  },
};

function load({ path, sha256 }) {
  const bytes = readFileSync(join(root, path));
  const sum = createHash("sha256").update(bytes).digest("hex");
  if (sum !== sha256) {
    throw new Error(`${path}: sha256 ${sum} is not the pinned input ${sha256}`);
  }
  return { text: bytes.toString("utf8"), sum };
}

const b36 = (n) => n.toString(36);

function encodeRanges(ranges) {
  let prev = 0;
  return ranges
    .map(([lo, hi]) => {
      const item = `${b36(lo - prev)}.${b36(hi - lo)}`;
      prev = hi;
      return item;
    })
    .join(",");
}

function encodeValueRanges(pairs) {
  const ranges = [];
  for (const [cp, value] of [...pairs].sort((a, b) => a[0] - b[0])) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] + 1 === cp && last[2] === value) last[1] = cp;
    else ranges.push([cp, cp, value]);
  }
  let prev = 0;
  return ranges
    .map(([lo, hi, value]) => {
      const item = `${b36(lo - prev)}.${b36(hi - lo)}.${b36(value)}`;
      prev = hi;
      return item;
    })
    .join(",");
}

function encodeMap(entries) {
  let prev = 0;
  return [...entries]
    .sort((a, b) => a[0] - b[0])
    .map(([cp, values]) => {
      const item = `${b36(cp - prev)}:${values.map(b36).join(".")}`;
      prev = cp;
      return item;
    })
    .join(",");
}

function encodeList(list) {
  let prev = 0;
  return [...list]
    .sort((a, b) => a - b)
    .map((cp) => {
      const item = b36(cp - prev);
      prev = cp;
      return item;
    })
    .join(",");
}

const folding = load(INPUTS.caseFolding);
const foldEntries = [];
for (const line of folding.text.split("\n")) {
  const fields = line.replace(/#.*/, "").split(";").map((f) => f.trim());
  if (fields.length < 3 || (fields[1] !== "C" && fields[1] !== "F")) continue;
  foldEntries.push([parseInt(fields[0], 16), fields[2].split(" ").map((h) => parseInt(h, 16))]);
}

const go = load(INPUTS.goTables);
const tables = JSON.parse(go.text);
if (tables.unicodeVersion !== VERSION || tables.normVersion !== VERSION) {
  throw new Error(`Go tables are Unicode ${tables.unicodeVersion}/${tables.normVersion}, want ${VERSION}`);
}

const out = `// Code generated by scripts/gen-unicode-tables.mjs. DO NOT EDIT.
// Unicode ${VERSION}. Inputs:
//   ${INPUTS.caseFolding.path} sha256 ${folding.sum}
//   ${INPUTS.goTables.path} sha256 ${go.sum} (${tables.goVersion}, x/text norm ${tables.normVersion})
// Encodings: ranges are "delta.length" base-36 items (delta from the previous
// range end); maps are "keyDelta:value.value"; lists are base-36 deltas.

export const UNICODE_VERSION = "${VERSION}";
export const ASSIGNED_RANGES = "${encodeRanges(tables.assigned)}";
export const FORMAT_RANGES = "${encodeRanges(tables.format)}";
export const COMBINING_CLASSES = "${encodeValueRanges(tables.combiningClass)}";
export const CANONICAL_DECOMPOSITIONS = "${encodeMap(tables.decompositions.map(([cp, ...m]) => [cp, m]))}";
export const PRIMARY_COMPOSITES = "${encodeList(tables.composites)}";
export const CASE_FOLDING = "${encodeMap(foldEntries)}";
export const STREAM_SAFE = "${encodeMap(tables.streamSafe.map(([cp, lead, trail]) => [cp, [lead, trail]]))}";
`;

const target = join(root, "src", "unicode-15-tables.ts");
writeFileSync(target, out);
console.log(`wrote ${target}`);
